package dev.grimholt.server.network;

import dev.grimholt.server.vanilla.*;
import java.io.*;
import java.util.*;

/**
 * Owns the 26.4-snapshot-3 configuration bootstrap. It deliberately consumes Grimholt's
 * generated reports rather than importing another server's packet classes.
 */
public final class VanillaConfigurationSync {
    private static final List<String> SYNCHRONIZED_REGISTRIES = List.of(
            "minecraft:worldgen/biome",
            "minecraft:chat_type",
            "minecraft:trim_pattern",
            "minecraft:trim_material",
            "minecraft:wolf_variant",
            "minecraft:wolf_sound_variant",
            "minecraft:pig_variant",
            "minecraft:pig_sound_variant",
            "minecraft:frog_variant",
            "minecraft:cat_variant",
            "minecraft:cat_sound_variant",
            "minecraft:cow_variant",
            "minecraft:cow_sound_variant",
            "minecraft:chicken_variant",
            "minecraft:chicken_sound_variant",
            "minecraft:zombie_nautilus_variant",
            "minecraft:painting_variant",
            "minecraft:dimension_type",
            "minecraft:damage_type",
            "minecraft:banner_pattern",
            "minecraft:enchantment",
            "minecraft:jukebox_song",
            "minecraft:instrument",
            "minecraft:test_environment",
            "minecraft:test_instance",
            "minecraft:dialog",
            "minecraft:world_clock",
            "minecraft:timeline",
            "minecraft:sulfur_cube_archetype"
    );

    private final VanillaGeneratedData generated;

    public VanillaConfigurationSync(VanillaGeneratedData generated) {
        this.generated = Objects.requireNonNull(generated, "generated");
    }

    /** Clientbound Select Known Packs. */
    public byte[] selectKnownPacks() {
        try {
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            VanillaProtocol26_2.writeVarInt(out, 1);
            VanillaProtocolCodec.writeString(out, "minecraft", 32767);
            VanillaProtocolCodec.writeString(out, "core", 32767);
            VanillaProtocolCodec.writeString(out, VanillaSnapshot.VERSION, 32767);
            return out.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /**
     * Reads the serverbound Select Known Packs payload. The exact client list is
     * intentionally retained only as a compatibility observation; registry
     * ordering remains server authoritative.
     */
    public Set<String> readKnownPacks(byte[] payload) throws IOException {
        ByteArrayInputStream in = new ByteArrayInputStream(payload);
        int count = VanillaProtocol26_2.readVarInt(in);
        if (count < 0 || count > 64) throw new IOException("Invalid known-pack count: " + count);
        Set<String> result = new LinkedHashSet<>();
        for (int i = 0; i < count; i++) {
            String namespace = VanillaProtocolCodec.readString(in, 32767);
            String id = VanillaProtocolCodec.readString(in, 32767);
            String version = VanillaProtocolCodec.readString(in, 32767);
            result.add(namespace + ":" + id + "@" + version);
        }
        if (in.available() != 0) throw new IOException("Trailing data in known-packs packet");
        return Set.copyOf(result);
    }

    /**
     * Builds Update Tags payloads directly from the tag files generated by Mojang's
     * 26.4 data generator. Nested #tag references are expanded before encoding.
     */
    public List<byte[]> updateTagsPackets() {
        Optional<String> index = generated.read("reports/tag_files.json");
        if (index.isEmpty()) return List.of();
        Map<String, Map<String, List<String>>> byRegistry = new LinkedHashMap<>();
        for (Object value : VanillaJson.array(VanillaJson.parse(index.get()))) {
            if (!(value instanceof String path)) continue;
            String registry = tagRegistryForPath(path);
            if (registry == null) continue;
            String json = generated.read(path).orElse(null);
            if (json == null) continue;
            Map<String,Object> tag = VanillaJson.object(VanillaJson.parse(json));
            Object values = tag.get("values");
            if (!(values instanceof List<?> list)) continue;
            String tagId = "minecraft:" + path.substring(path.indexOf("/tags/") + 6)
                    .replaceFirst("^" + registryPath(registry) + "/", "")
                    .replaceAll("\\.json$", "");
            List<String> ids = new ArrayList<>();
            for (Object entry : list) {
                if (entry instanceof String s) ids.add(s);
                else if (entry instanceof Map<?,?> map && map.get("id") instanceof String s) ids.add(s);
            }
            byRegistry.computeIfAbsent(registry, ignored -> new LinkedHashMap<>()).put(tagId, ids);
        }

        if (byRegistry.isEmpty()) return List.of();

        // Snapshot 3 has one Update Tags packet containing a map of registries.
        // Sending one packet per registry misaligns the client's packet decoder.
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        try {
            VanillaProtocol26_2.writeVarInt(out, byRegistry.size());
            for (var registryEntry : byRegistry.entrySet()) {
                String registry = registryEntry.getKey();
                Map<String,Integer> ids = registryIds(registry);
                Map<String,List<String>> tags = registryEntry.getValue();
                Map<String,List<String>> expanded = new LinkedHashMap<>();
                for (String tagId : tags.keySet()) {
                    expanded.put(tagId, resolveTag(tagId, tags, new LinkedHashSet<>()));
                }

                VanillaProtocolCodec.writeIdentifier(out, registry);
                VanillaProtocol26_2.writeVarInt(out, expanded.size());
                for (var tag : expanded.entrySet()) {
                    VanillaProtocolCodec.writeIdentifier(out, tag.getKey());
                    LinkedHashSet<Integer> resolved = new LinkedHashSet<>();
                    for (String id : tag.getValue()) {
                        Integer numeric = ids.get(id);
                        if (numeric != null) resolved.add(numeric);
                    }
                    VanillaProtocol26_2.writeVarInt(out, resolved.size());
                    for (int id : resolved) VanillaProtocol26_2.writeVarInt(out, id);
                }
            }
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot encode 26.4 Update Tags", e);
        }
        return List.of(out.toByteArray());
    }

    private static List<String> resolveTag(String tagId,
                                            Map<String,List<String>> tags,
                                            Set<String> visiting) {
        if (!visiting.add(tagId)) {
            throw new IllegalStateException("Cyclic vanilla tag reference: " + visiting + " -> " + tagId);
        }
        LinkedHashSet<String> result = new LinkedHashSet<>();
        for (String value : tags.getOrDefault(tagId, List.of())) {
            if (value.startsWith("#")) {
                String nested = value.substring(1);
                if (!nested.contains(":")) nested = "minecraft:" + nested;
                result.addAll(resolveTag(nested, tags, visiting));
            } else {
                result.add(value);
            }
        }
        visiting.remove(tagId);
        return List.copyOf(result);
    }

    private Map<String,Integer> registryIds(String registry) {
        Map<String,Object> root = VanillaJson.object(VanillaJson.parse(generated.require("reports/registries.json")));
        Object raw = root.get(registry);
        if (!(raw instanceof Map<?,?> map) || !(map.get("entries") instanceof Map<?,?> entries)) return Map.of();
        Map<String,Integer> ids = new HashMap<>();
        for (var entry : entries.entrySet()) {
            if (!(entry.getKey() instanceof String key) || !(entry.getValue() instanceof Map<?,?> value)) continue;
            if (value.get("protocol_id") instanceof Number n) ids.put(key, n.intValue());
        }
        return ids;
    }

    private static String tagRegistryForPath(String path) {
        int marker = path.indexOf("/tags/");
        if (marker < 0) return null;
        String rest = path.substring(marker + 6);
        int slash = rest.indexOf('/');
        if (slash < 0) return null;
        return switch (rest.substring(0, slash)) {
            // Mojang's data-pack directories use singular registry names.
            case "block", "blocks" -> "minecraft:block";
            case "item", "items" -> "minecraft:item";
            case "fluid", "fluids" -> "minecraft:fluid";
            case "entity_type", "entity_types" -> "minecraft:entity_type";
            case "game_event", "game_events" -> "minecraft:game_event";
            default -> null;
        };
    }

    private static String registryPath(String registry) {
        return switch (registry) {
            case "minecraft:block" -> "block";
            case "minecraft:item" -> "item";
            case "minecraft:fluid" -> "fluid";
            case "minecraft:entity_type" -> "entity_type";
            case "minecraft:game_event" -> "game_event";
            default -> "";
        };
    }

    /**
     * Registry entry payloads may omit their vanilla NBT only when the client
     * explicitly confirms the exact core pack advertised by this server.
     */
    public void requireCompatibleKnownPacks(Set<String> knownPacks) throws IOException {
        Objects.requireNonNull(knownPacks, "knownPacks");
        String expected = "minecraft:core@" + VanillaSnapshot.VERSION;
        if (!knownPacks.contains(expected)) {
            throw new IOException("Client did not acknowledge required vanilla pack " + expected
                    + "; refusing to send registry entries without their canonical NBT values. "
                    + "Client acknowledged: " + knownPacks);
        }
    }

    /**
     * Builds Registry Data payloads. For vanilla's core known pack the client
     * already owns the canonical entry values, so the Grimholt wire contract
     * may send entries with the optional NBT bit cleared. This keeps the
     * bootstrap deterministic while leaving custom-data overrides for the
     * future data-pack layer.
     */
    public List<byte[]> registryDataPackets() {
        // Never silently send finish_configuration when the generated registry
        // report is unavailable: that creates a superficially successful login
        // sequence which the vanilla client cannot complete.
        generated.requireAvailable();
        Map<String,Object> root = VanillaJson.object(
                VanillaJson.parse(generated.require("reports/registries.json")));
        List<byte[]> packets = new ArrayList<>();
        List<String> missing = new ArrayList<>();

        for (String registryId : SYNCHRONIZED_REGISTRIES) {
            Object raw = root.get(registryId);
            if (!(raw instanceof Map<?,?> rawMap)) {
                missing.add(registryId + " (registry absent from report)");
                continue;
            }
            Object entriesValue = rawMap.get("entries");
            if (!(entriesValue instanceof Map<?,?> entries)) {
                missing.add(registryId + " (entries absent from report)");
                continue;
            }

            try {
                ByteArrayOutputStream out = new ByteArrayOutputStream();
                VanillaProtocolCodec.writeIdentifier(out, registryId);
                // The wire order defines the client's numeric registry IDs. Never
                // alphabetically sort registry keys: preserve Mojang's protocol_id order.
                List<Map.Entry<String, Integer>> orderedEntries = new ArrayList<>();
                for (var entry : entries.entrySet()) {
                    if (!(entry.getKey() instanceof String name)
                            || !(entry.getValue() instanceof Map<?, ?> metadata)
                            || !(metadata.get("protocol_id") instanceof Number protocolId)) {
                        continue;
                    }
                    orderedEntries.add(Map.entry(name, protocolId.intValue()));
                }
                orderedEntries.sort(Map.Entry.comparingByValue());

                // Empty dynamic registries are valid: send their registry ID
                // and a zero entry count rather than treating them as missing data.
                VanillaProtocol26_2.writeVarInt(out, orderedEntries.size());
                for (var entry : orderedEntries) {
                    VanillaProtocolCodec.writeIdentifier(out, entry.getKey());
                    // The negotiated minecraft:core pack supplies the canonical vanilla
                    // registry values on the client; this entry only establishes ordering.
                    VanillaProtocolCodec.writeBoolean(out, false);
                }
                packets.add(out.toByteArray());
            } catch (IOException e) {
                throw new UncheckedIOException("Cannot encode registry " + registryId, e);
            }
        }

        if (!missing.isEmpty()) {
            throw new IllegalStateException(
                    "Incomplete Minecraft 26.4 registry synchronization; refusing to finish configuration. "
                    + "Missing/malformed: " + String.join(", ", missing)
                    + ". Verify the pinned reports/registries.json and the registry list against Snapshot 3.");
        }
        if (packets.isEmpty()) {
            throw new IllegalStateException(
                    "No 26.4 registry-data packets could be built from the generated reports/registries.json.");
        }
        if (packets.stream().allMatch(packet -> packet.length == 0)) {
            throw new IllegalStateException("Registry-data encoder produced only empty packets.");
        }
        return List.copyOf(packets);
    }
}
